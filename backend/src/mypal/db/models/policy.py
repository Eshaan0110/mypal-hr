"""The policy register: policies, their versions, where each version applies, and its chunks.

Most lifecycle rules are enforced by the database itself (CHECK constraints and a partial unique
index), so a bug in application code cannot, for example, make two versions of one policy active.
"""

import uuid
from datetime import date, datetime

from sqlalchemy import (
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from mypal.db.base import Base, created_at, uuid_pk
from mypal.db.models.enums import ChunkKind, PolicyVersionStatus, str_enum


class Policy(Base):
    """A policy's stable identity (e.g. "leave-policy"), independent of any one version."""

    __tablename__ = "policies"
    __table_args__ = (
        CheckConstraint("policy_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$'", name="policy_key_format"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    policy_key: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    title: Mapped[str] = mapped_column(Text, nullable=False)
    # The HR content owner responsible for this policy (name or role, as HR records it).
    owner: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = created_at()

    versions: Mapped[list["PolicyVersion"]] = relationship(back_populates="policy")


class PolicyVersion(Base):
    __tablename__ = "policy_versions"
    __table_args__ = (
        UniqueConstraint("policy_id", "version_label", name="uq_policy_versions_label"),
        # Lets the self-reference below require that a replacement belongs to the same policy.
        UniqueConstraint("policy_id", "id", name="uq_policy_versions_policy_id_id"),
        ForeignKeyConstraint(
            ["policy_id", "supersedes_version_id"],
            ["policy_versions.policy_id", "policy_versions.id"],
            name="fk_policy_versions_supersedes_same_policy",
        ),
        # At most ONE active version per policy.
        Index(
            "uq_policy_versions_one_active",
            "policy_id",
            unique=True,
            postgresql_where=text("status = 'active'"),
        ),
        Index("ix_policy_versions_status", "status"),
        # Four-eyes rule: nobody approves their own upload.
        CheckConstraint("approved_by IS NULL OR approved_by <> created_by", name="four_eyes"),
        CheckConstraint(
            "(approved_by IS NULL) = (approved_at IS NULL)", name="approval_fields_together"
        ),
        CheckConstraint(
            "status NOT IN ('approved', 'active', 'superseded') OR approved_by IS NOT NULL",
            name="approved_states_have_approver",
        ),
        CheckConstraint(
            "status IN ('draft', 'rejected') OR effective_from IS NOT NULL",
            name="reviewed_states_have_effective_date",
        ),
        CheckConstraint(
            "status NOT IN ('active', 'superseded') OR published_at IS NOT NULL",
            name="published_states_have_published_at",
        ),
        CheckConstraint("source_sha256 ~ '^[0-9a-f]{64}$'", name="source_sha256_format"),
        CheckConstraint(
            "supersedes_version_id IS NULL OR supersedes_version_id <> id",
            name="not_self_superseding",
        ),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    policy_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("policies.id", ondelete="RESTRICT"), nullable=False
    )
    version_label: Mapped[str] = mapped_column(String(32), nullable=False)
    status: Mapped[PolicyVersionStatus] = mapped_column(
        str_enum(PolicyVersionStatus, "status"),
        nullable=False,
        default=PolicyVersionStatus.DRAFT,
        server_default=PolicyVersionStatus.DRAFT.value,
    )
    effective_from: Mapped[date | None] = mapped_column(Date)
    # Link employees can open (intranet URL). Shown in citations; never generated by the LLM.
    source_link: Mapped[str | None] = mapped_column(Text)
    source_filename: Mapped[str] = mapped_column(Text, nullable=False)
    source_sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    # Ingestion quality report (e.g. "page 3 has no text layer - likely scanned").
    parse_report: Mapped[dict | None] = mapped_column(JSONB)
    supersedes_version_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))

    # Actor IDs come from the identity provider (no local users table).
    created_by: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = created_at()
    approved_by: Mapped[str | None] = mapped_column(Text)
    approved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    policy: Mapped[Policy] = relationship(back_populates="versions")
    scopes: Mapped[list["PolicyVersionScope"]] = relationship(back_populates="version")
    chunks: Mapped[list["Chunk"]] = relationship(back_populates="version", order_by="Chunk.ordinal")


class PolicyVersionScope(Base):
    """Who a version applies to. One row per (company, location, category) combination.
    NULL location or category means "all locations" / "all categories" within that company."""

    __tablename__ = "policy_version_scopes"
    __table_args__ = (
        UniqueConstraint(
            "version_id",
            "company_code",
            "location_code",
            "category_code",
            name="uq_policy_version_scopes_combination",
            # Treat NULL ("all") as a value, so the same "all locations" row cannot repeat.
            postgresql_nulls_not_distinct=True,
        ),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    version_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("policy_versions.id", ondelete="CASCADE"), nullable=False
    )
    company_code: Mapped[str] = mapped_column(
        String(32), ForeignKey("companies.code"), nullable=False
    )
    location_code: Mapped[str | None] = mapped_column(String(32), ForeignKey("locations.code"))
    category_code: Mapped[str | None] = mapped_column(
        String(32), ForeignKey("employee_categories.code")
    )

    version: Mapped[PolicyVersion] = relationship(back_populates="scopes")


class Chunk(Base):
    """A retrievable passage of a policy version. Postgres holds the text (source of truth);
    the search index (Qdrant, Phase 4) can always be rebuilt from this table."""

    __tablename__ = "chunks"
    __table_args__ = (
        UniqueConstraint("version_id", "ordinal", name="uq_chunks_version_ordinal"),
        CheckConstraint("length(btrim(text)) > 0", name="text_not_blank"),
        CheckConstraint("page_start IS NULL OR page_start >= 1", name="page_start_positive"),
        CheckConstraint(
            "page_end IS NULL OR (page_start IS NOT NULL AND page_end >= page_start)",
            name="page_range_valid",
        ),
        CheckConstraint("content_hash ~ '^[0-9a-f]{64}$'", name="content_hash_format"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    version_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("policy_versions.id", ondelete="CASCADE"), nullable=False
    )
    ordinal: Mapped[int] = mapped_column(Integer, nullable=False)
    kind: Mapped[ChunkKind] = mapped_column(
        str_enum(ChunkKind, "kind"), nullable=False, default=ChunkKind.TEXT
    )
    text: Mapped[str] = mapped_column(Text, nullable=False)
    # e.g. ["4. Leave", "4.2 Casual leave"] - used for citations and as retrieval context.
    heading_path: Mapped[list[str]] = mapped_column(
        ARRAY(Text), nullable=False, default=list, server_default="{}"
    )
    section_ref: Mapped[str | None] = mapped_column(Text)
    page_start: Mapped[int | None] = mapped_column(Integer)
    page_end: Mapped[int | None] = mapped_column(Integer)
    content_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    created_at: Mapped[datetime] = created_at()

    version: Mapped[PolicyVersion] = relationship(back_populates="chunks")
